import React from 'react'
import { render, screen, fireEvent, waitFor, within, cleanup } from '@testing-library/react'
import { FollowupPane } from '../src/followup-pane.jsx'
import { followupStrings } from '../src/followup-i18n.mjs'
import { openFollowupStore } from '../src/followup-indexeddb.mjs'
import { applyFollowupAction, createFollowupTask } from '../src/followup-tasks.mjs'

const t = key => followupStrings.zh[key] || key
const name = new URL(location.href).searchParams.get('db')
const check = (value, message) => { if (!value) throw Error(message) }
const route = { connectionId:'test-source', profile:'default', targetProfile:'default', mode:'local' }
let opens = 0
let focusedId = 'synthetic-session'
let focusedOwner = route
const host = { state:{ focusedStoredSessionId:{get:()=> focusedId}, focusedSessionOwner:{get:()=>focusedOwner} }, profileRoutes:async()=>[route, {...route, connectionId:'other-source'}], openExactSession:async()=>{ opens++ } }

async function run() {
  check(name?.startsWith('followup_isolated_test_'), 'isolated database required')
  let app = render(<FollowupPane host={host} t={t} storageName={name}/>)
  await screen.findByText('尚未跟踪事项')
  fireEvent.click(screen.getByRole('button', {name:'新建事项'}))
  const form = screen.getByRole('form', {name:'新建事项'})
  fireEvent.change(within(form).getByLabelText('事项名称'), {target:{value:'整理并行任务'}})
  fireEvent.change(within(form).getByLabelText('说明'), {target:{value:'核对各个会话'}})
  fireEvent.change(within(form).getByLabelText('备注'), {target:{value:'等待反馈的记录'}})
  fireEvent.change(within(form).getByLabelText('剩余步骤'), {target:{value:'先核对进度'}})
  fireEvent.click(within(form).getByRole('button', {name:'高'}))
  fireEvent.click(within(form).getByRole('button', {name:'保存事项'}))
  await screen.findByRole('heading', {name:'整理并行任务'})
  check(screen.getByText('核对各个会话'), 'description was not displayed')
  check(screen.getByText('等待反馈的记录'), 'notes were not displayed')
  let store = await openFollowupStore(indexedDB, name)
  let rows = await store.list()
  check(rows.length === 1 && rows[0].task.primary === null && rows[0].task.status === 'todo' && rows[0].task.priority === 'high', 'standalone record was not saved')
  store.close(); app.unmount(); cleanup()
  app = render(<FollowupPane host={host} t={t} storageName={name}/>)
  await screen.findByRole('heading', {name:'整理并行任务'})
  check(screen.getByText('等待反馈的记录'), 'notes disappeared after reopening')
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/进行中 · 0/}))
  check(screen.getByText('当前筛选条件下没有事项'), 'empty filtered view is misleading')
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/未完成 · 1/}))
  fireEvent.click(screen.getByRole('button', {name:'绑定当前会话'}))
  await waitFor(() => check(screen.queryByRole('button', {name:'打开主会话'}), 'binding did not reach the view'))
  store = await openFollowupStore(indexedDB, name)
  rows = await store.list()
  check(rows[0].task.primary?.storedId === 'synthetic-session' && rows[0].task.status === 'todo', 'binding did not persist or changed status')
  store.close()
  check(screen.getByRole('button', {name:'打开主会话'}).disabled, 'unverified session open was enabled')
  check(opens === 0 && screen.getByRole('heading', {name:'整理并行任务'}), 'disabled navigation opened a session or removed the task')
  await waitFor(() => check(!screen.getByRole('button', {name:'编辑事项'}).disabled, 'binding did not settle'))
  fireEvent.click(screen.getByRole('button', {name:'重新绑定当前会话'}))
  await screen.findByRole('alertdialog', {name:'重新绑定当前会话'})
  focusedId = 'different-session'
  fireEvent.click(screen.getByRole('button', {name:'确认修改'}))
  await screen.findByText(/Focused session changed/)
  store = await openFollowupStore(indexedDB, name)
  rows = await store.list()
  check(rows[0].task.primary?.storedId === 'synthetic-session', 'focus change silently rebound the task')
  store.close()
  fireEvent.click(screen.getByRole('button', {name:'取消'}))
  focusedId = 'synthetic-session'
  fireEvent.click(screen.getByRole('button', {name:'编辑事项'}))
  fireEvent.click(screen.getByRole('button', {name:'取消'}))
  check(!screen.queryByText(/Focused session changed/), 'old failure was not cleared before second case')
  fireEvent.click(screen.getByRole('button', {name:'重新绑定当前会话'}))
  await screen.findByRole('alertdialog', {name:'重新绑定当前会话'})
  focusedOwner = { ...route, connectionId: 'other-source' }
  fireEvent.click(screen.getByRole('button', {name:'确认修改'}))
  await screen.findByText(/Focused session changed/)
  store = await openFollowupStore(indexedDB, name)
  rows = await store.list()
  check(rows[0].task.primary?.connectionId === 'test-source', 'same-ID owner change silently rebound the task')
  store.close()
  fireEvent.click(screen.getByRole('button', {name:'取消'}))
  focusedOwner = route
  fireEvent.click(screen.getByRole('button', {name:'编辑事项'}))
  const edit = screen.getByRole('form', {name:'编辑事项'})
  fireEvent.click(within(edit).getByRole('button', {name:'等待中'}))
  fireEvent.click(within(edit).getByRole('button', {name:'保存修改'}))
  await waitFor(() => check(!screen.queryByRole('form', {name:'编辑事项'}), 'edit did not finish'))
  await waitFor(() => check(!screen.getByRole('button', {name:'编辑事项'}).disabled, 'save did not settle'))
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/等待中 ·/}))
  check(screen.getByRole('heading', {name:'整理并行任务'}), 'waiting filter lost task')
  fireEvent.change(screen.getByRole('textbox', {name:'搜索事项 / 关联会话'}), {target:{value:'核对各个会话'}})
  check(screen.getByRole('heading', {name:'整理并行任务'}), 'description search missed task')
  fireEvent.click(screen.getByRole('button', {name:'删除事项'}))
  fireEvent.click(screen.getByRole('button', {name:'取消'}))
  check(screen.getByRole('heading', {name:'整理并行任务'}), 'cancelled deletion removed task')
  fireEvent.click(screen.getByRole('button', {name:'删除事项'}))
  fireEvent.click(screen.getByRole('button', {name:'确认删除'}))
  await waitFor(() => check(!screen.queryByRole('heading', {name:'整理并行任务'}), 'deletion did not update the list'))
  store = await openFollowupStore(indexedDB, name)
  rows = await store.list()
  check(rows.length === 0, 'deleted task survived storage readback')
  const seed = (id, title, status, priority, at) => createFollowupTask({id, title, primary:null, related:[], nextSteps:[], status, priority}, at)
  await store.create(seed('a', '待处理甲', 'todo', 'high', 1000))
  await store.create(seed('b', '等待乙', 'waiting', 'low', 2000))
  await store.create(seed('c', '正在处理丙', 'in_progress', 'urgent', 3000))
  const completed = applyFollowupAction(seed('d', '完成丁', 'todo', 'normal', 4000), {type:'accept', at:5000, note:'已核对'})
  await store.create(completed)
  store.close(); app.unmount(); cleanup()
  app = render(<FollowupPane host={host} t={t} storageName={name}/> )
  await screen.findByRole('button', {name:/正在处理丙/})
  let list = [...document.querySelectorAll('.list > button')].map(node => node.textContent)
  check(list.length === 3 && list[0].includes('正在处理丙') && list[1].includes('等待乙') && list[2].includes('待处理甲'), 'updated-time order is wrong')
  fireEvent.click(within(document.querySelector('[aria-label="排序"]')).getByRole('button', {name:'优先级'}))
  list = [...document.querySelectorAll('.list > button')].map(node => node.textContent)
  check(list[0].includes('正在处理丙') && list[1].includes('待处理甲') && list[2].includes('等待乙'), 'priority order is wrong')
  fireEvent.click(within(document.querySelector('[aria-label="优先级筛选"]')).getByRole('button', {name:'高'}))
  list = [...document.querySelectorAll('.list > button')].map(node => node.textContent)
  check(list.length === 1 && list[0].includes('待处理甲'), 'priority filter is wrong')
  fireEvent.click(within(document.querySelector('[aria-label="优先级筛选"]')).getByRole('button', {name:'不限'}))
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/进行中 · 1/}))
  check(screen.getByRole('heading', {name:'正在处理丙'}) && !screen.queryByRole('button', {name:/待处理甲/}), 'in-progress filter is wrong')
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/已完成 · 1/}))
  check(screen.getByRole('heading', {name:'完成丁'}), 'completed filter is wrong')
  fireEvent.click(within(document.querySelector('.tabs')).getByRole('button', {name:/全部 · 4/}))
  check(document.querySelectorAll('.list > button').length === 4, 'all filter omitted tasks')
  app.unmount(); cleanup()
  let routeCalls = 0, ordinaryOpens = 0
  const partialHost = { state:{ focusedStoredSessionId:{get:()=> 'partial-session'}, focusedSessionOwner:{get:()=>({connectionId:'test-source', profile:'default'})} }, profileRoutes:async()=>{ routeCalls++; return [route] }, openSession:async()=>{ ordinaryOpens++ } }
  app = render(<FollowupPane host={partialHost} t={t} storageName={`${name}_partial`}/> )
  await screen.findByText('尚未跟踪事项')
  fireEvent.click(screen.getByRole('button', {name:'跟踪当前会话'}))
  const partialForm = await screen.findByRole('form', {name:'跟踪会话'})
  check(within(partialForm).getByText('来源未核实，暂不能从面板打开'), 'unverified source was not disclosed before saving')
  fireEvent.change(within(partialForm).getByLabelText('事项名称'), {target:{value:'需要继续的会话'}})
  fireEvent.click(within(partialForm).getByRole('button', {name:'保存跟踪'}))
  await screen.findByRole('heading', {name:'需要继续的会话'})
  check(screen.getByText('来源未核实，暂不能从面板打开'), 'unverified source was hidden')
  check(screen.getByRole('button', {name:'打开主会话'}).disabled, 'unverified session open was enabled')
  check(routeCalls === 0 && ordinaryOpens === 0, 'unverified capture contacted or opened a backend')
  store = await openFollowupStore(indexedDB, `${name}_partial`)
  rows = await store.list()
  check(rows[0].task.primary?.storedId === 'partial-session' && rows[0].task.primary?.unverified === true && !('targetProfile' in rows[0].task.primary), 'partial source was not persisted honestly')
  store.close(); app.unmount(); cleanup()
  const noExactHost = { state:{ focusedStoredSessionId:{get:()=> 'legacy-session'}, focusedSessionOwner:{get:()=>route} }, profileRoutes:async()=>[route], openSession:async()=>{ ordinaryOpens++ } }
  const blockedDb = `${name}_no_exact`
  store = await openFollowupStore(indexedDB, blockedDb)
  await store.create(createFollowupTask({id:'bound', title:'已绑定会话', primary:{...route,storedId:'legacy-session',storeInstanceId:'copied-store'}, related:[], nextSteps:[], status:'todo', priority:'normal'}, 1000))
  store.close()
  app = render(<FollowupPane host={noExactHost} t={t} storageName={blockedDb}/> )
  await screen.findByRole('heading', {name:'已绑定会话'})
  check(screen.getByRole('button', {name:'打开主会话'}).disabled, 'host without exact navigation allowed open')
  check(screen.getByText('此版本无法核实会话来源，已阻止打开以避免进入错误会话。'), 'missing source verification was not explained')
  check(ordinaryOpens === 0, 'ordinary openSession was used as a fallback')
  app.unmount(); cleanup()
  return {status:'PASS', cases:['standalone creation', 'description and priority', 'storage reopen', 'bind current session without changing status', 'unverified open disabled and task retained', 'manual waiting state', 'status filter', 'description search', 'delete cancel', 'delete readback', 'updated and priority sorting', 'priority filter', 'in-progress/completed/all filters', 'partial Desktop owner saved without guessing or opening']}
}
run().then(result => document.querySelector('#result').textContent = JSON.stringify(result)).catch(error => document.querySelector('#result').textContent = JSON.stringify({status:'FAIL', error:String(error), stack:error?.stack}))